local helper = require("helper")

describe("decoded cover ownership", function()
	local CoverMemory

	local function bitmap(stride, height)
		return {
			stride = stride, h = height, freed = 0,
			free = function(self)
				self.freed = self.freed + 1
				assert.equals(1, self.freed, "bitmap freed twice")
			end,
		}
	end

	before_each(function()
		helper.reset()
		CoverMemory = helper.load("services.cover_memory")
	end)
	after_each(helper.reset)

	it("budgets actual padded row bytes and makes evicted entries reloadable", function()
		local memory = CoverMemory:new(80)
		local first, second = {}, {}
		local a, b = bitmap(16, 3), bitmap(16, 3)
		memory:add(first, a)()
		local release = memory:add(second, b)
		assert.equals(48, memory.bytes)
		assert.equals(1, a.freed)
		assert.equals(0, b.freed)
		assert.is_nil(first.cover_bb)
		assert.is_true(first.lazy_load_cover)
		assert.equals(b, second.cover_bb)
		release()
		memory:clear()
		assert.equals(0, memory.bytes)
	end)

	it("never evicts visible or borrowed buffers even over budget or on clear", function()
		local memory = CoverMemory:new(100)
		local a, b = bitmap(12, 10), bitmap(16, 10)
		local release_a = memory:add({}, a)
		local release_b = memory:add({}, b)
		local release_dialog = memory:pin(a)
		release_a()
		memory:clear()
		assert.equals(280, memory.bytes)
		assert.equals(280, memory.pinned_bytes)
		assert.equals(0, a.freed)
		assert.equals(0, b.freed)
		release_b()
		assert.equals(1, b.freed)
		assert.equals(0, a.freed)
		release_dialog()
		release_dialog()
		assert.equals(1, a.freed)
		assert.equals(0, memory.bytes)
		assert.equals(0, memory.pinned_bytes)
		assert.same({}, memory.records)
		assert.same({}, memory.entries)
	end)

	it("evicts the least recently used unpinned rendering", function()
		local memory = CoverMemory:new(65)
		local first, second, third = {}, {}, {}
		local a, b, c = bitmap(3, 10), bitmap(3, 10), bitmap(3, 10)
		memory:add(first, a)()
		memory:add(second, b)()
		assert.equals(a, memory:get(first))
		memory:add(third, c)()
		assert.equals(0, a.freed)
		assert.equals(1, b.freed)
		assert.equals(0, c.freed)
		assert.equals(60, memory.bytes)
	end)

	it("keeps a borrowed old rendering alive without clearing its replacement", function()
		local memory = CoverMemory:new(200)
		local entry = {}
		local old, replacement = bitmap(4, 10), bitmap(8, 20)
		local release_old = memory:add(entry, old)
		local release_new = memory:add(entry, replacement)
		assert.equals(0, old.freed)
		release_old()
		assert.equals(1, old.freed)
		assert.equals(replacement, entry.cover_bb)
		assert.equals(160, memory.bytes)
		memory:clear()
		assert.equals(0, replacement.freed)
		release_new()
		assert.equals(1, replacement.freed)
		assert.equals(0, memory.bytes)
	end)

	it("releases dialog-only buffers as soon as their last user closes", function()
		local memory = CoverMemory:new(1000)
		local cover = bitmap(10, 20)
		local release_render = memory:add(nil, cover)
		local release_widget = memory:pin(cover)
		release_render()
		assert.equals(0, cover.freed)
		assert.equals(200, memory.pinned_bytes)
		release_widget()
		assert.equals(1, cover.freed)
		assert.equals(0, memory.bytes)
		assert.same({}, memory.records)
	end)
end)
